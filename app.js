function showRoute(route) {
  Object.entries(pages).forEach(([key, page]) => {
    page.hidden = key !== route;
  });

  const known = route !== "*";
  const titleRoute = known ? route : "/";
  document.querySelector("[data-testid='text-current-page']").textContent = pageTitles[titleRoute];
  document.querySelectorAll("[data-nav]").forEach((link) => {
    const active = known && link.dataset.nav === route;
    link.classList.toggle("mv-nav-link-active", active && link.classList.contains("mv-nav-link"));
    link.classList.toggle(
      "mv-mobile-nav-link-active",
      active && link.classList.contains("mv-mobile-nav-link"),
    );
    if (active) link.setAttribute("aria-current", "page");
    else link.removeAttribute("aria-current");
  });

  if (route === "/") renderOverview();
  if (route === "/transactions") renderTransactions();
  if (route === "/add" && lastRoute !== "/add") prepareAddForm();
  if (route === "/insights") renderInsights();
  if (route !== "/transactions") {
    filters = { ...defaultFilters };
    document.getElementById("save-notice").hidden = true;
  }
  if (route !== "/insights") selectedMonth = "";
  lastRoute = route;
}

