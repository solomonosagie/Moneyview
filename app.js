document.getElementById("transaction-form").addEventListener("submit", (event) => {
  event.preventDefault();
  const form = event.currentTarget;
  const values = {
    accountId: form.accountId.value,
    date: form.date.value,
    description: form.description.value,
    category: form.category.value,
    amount: form.amount.value,
    type: form.type.value,
  };
  const errors = validateTransaction(values);
  setFieldError("transaction-account", errors.accountId);
  setFieldError("transaction-date", errors.date);
  setFieldError("transaction-description", errors.description);
  setFieldError("transaction-category", errors.category);
  setFieldError("transaction-amount", errors.amount);

  const saveError = document.getElementById("save-error");
  if (Object.keys(errors).length > 0) {
    saveError.hidden = true;
    return;
  }

  const record = {
    id: `added-${Date.now()}`,
    accountId: values.accountId,
    date: values.date,
    description: values.description.trim(),
    category: values.category,
    amount: Number(values.amount),
    type: values.type,
  };

  try {
    const added = loadAdded();
    added.push(record);
    localStorage.setItem(ADDED_KEY, JSON.stringify(added));
  } catch (error) {
    saveError.hidden = false;
    document.getElementById("save-error-text").textContent =
      error instanceof Error
        ? error.message
        : "We could not save this transaction. Your entries are still here; try again.";
    return;
  }

  saveError.hidden = true;
  form.reset();
  document.getElementById("transaction-date").value = getLocalToday();
  const out = form.querySelector('input[name="type"][value="out"]');
  if (out) out.checked = true;
  prepareAddForm();
  sessionStorage.setItem(
    NOTICE_KEY,
    JSON.stringify({
      description: record.description,
      amount: record.amount,
      type: record.type,
    }),
  );
  location.hash = "#/transactions";
});

