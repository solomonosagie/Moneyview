function formatDate(value) {
  const date = new Date(`${String(value ?? "").slice(0, 10)}T00:00:00Z`);
  if (Number.isNaN(date.getTime())) return "Date unavailable";
  return dateFormatter.format(date);
}

function getCategoryLabel(category) {
  if (typeof category !== "string" || category.trim() === "") return "Uncategorised";
  return category.trim();
}

function compareValues(left, right, sortBy) {
  if (sortBy === "amount") {
    const leftAmount = Number.isFinite(left.amount) ? left.amount : 0;
    const rightAmount = Number.isFinite(right.amount) ? right.amount : 0;
    return leftAmount - rightAmount;
  }

  const valueFor = (transaction) => {
    if (sortBy === "category") return getCategoryLabel(transaction.category);
    if (sortBy === "description") return String(transaction.description ?? "");
    return String(transaction.date ?? "");
  };

  return valueFor(left).localeCompare(valueFor(right), "en-NG", {
    numeric: true,
    sensitivity: "base",
  });
}

function filterTransactions(transactions, activeFilters = {}) {
  if (!Array.isArray(transactions)) return [];

  const search = String(activeFilters.search ?? "").trim().toLocaleLowerCase("en-NG");
  const selectedCategory = String(activeFilters.category ?? "")
    .trim()
    .toLocaleLowerCase("en-NG");
  const dateFrom = String(activeFilters.dateFrom ?? "");
  const dateTo = String(activeFilters.dateTo ?? "");
  const sortBy = activeFilters.sortBy ?? "date";
  const direction = activeFilters.sortDirection === "asc" ? 1 : -1;

  return transactions
    .map((transaction, index) => ({ transaction, index }))
    .filter(({ transaction }) => {
      if (!transaction || typeof transaction !== "object") return false;
      const category = getCategoryLabel(transaction.category);
      const description = String(transaction.description ?? "");
      const matchesSearch =
        !search ||
        `${description} ${category}`.toLocaleLowerCase("en-NG").includes(search);
      const matchesCategory =
        !selectedCategory ||
        selectedCategory === "all" ||
        category.toLocaleLowerCase("en-NG") === selectedCategory;
      const date = String(transaction.date ?? "");
      const validDate = /^\d{4}-\d{2}-\d{2}$/.test(date);
      const matchesFrom = !dateFrom || (validDate && date >= dateFrom);
      const matchesTo = !dateTo || (validDate && date <= dateTo);
      return matchesSearch && matchesCategory && matchesFrom && matchesTo;
    })
    .sort((left, right) => {
      const comparison = compareValues(left.transaction, right.transaction, sortBy);
      if (comparison !== 0) return comparison * direction;
      return (left.index - right.index) * direction;
    })
    .map(({ transaction }) => transaction);
}

function spendByCategory(transactions, month) {
  if (!Array.isArray(transactions) || !/^\d{4}-\d{2}$/.test(String(month))) return [];

  const totals = new Map();
  for (const transaction of transactions) {
    if (
      !transaction ||
      transaction.type !== "out" ||
      typeof transaction.date !== "string" ||
      transaction.date.slice(0, 7) !== month ||
      !Number.isFinite(transaction.amount) ||
      transaction.amount <= 0
    ) {
      continue;
    }

    const category = getCategoryLabel(transaction.category);
    const key = category.toLocaleLowerCase("en-NG");
    const previous = totals.get(key);
    totals.set(key, {
      category: previous?.category ?? category,
      amount: (previous?.amount ?? 0) + transaction.amount,
    });
  }

  const totalSpend = [...totals.values()].reduce((sum, entry) => sum + entry.amount, 0);
  return [...totals.values()]
    .map((entry) => ({
      ...entry,
      share: totalSpend > 0 ? entry.amount / totalSpend : 0,
    }))
    .sort(
      (left, right) =>
        right.amount - left.amount || left.category.localeCompare(right.category, "en-NG"),
    );
}

function loadAdded() {
  try {
    const parsed = JSON.parse(localStorage.getItem(ADDED_KEY) || "[]");
    return Array.isArray(parsed) ? parsed : [];
  } catch {
    return [];
  }
}

function transactions() {
  return MONEYVIEW_SEED.transactions.concat(loadAdded());
}

function accounts() {
  const adjustments = new Map();
  for (const transaction of loadAdded()) {
    if (!transaction || !Number.isFinite(transaction.amount)) continue;
    const delta = transaction.type === "in" ? transaction.amount : -transaction.amount;
    adjustments.set(
      transaction.accountId,
      (adjustments.get(transaction.accountId) || 0) + delta,
    );
  }

  return MONEYVIEW_SEED.accounts.map((account) => ({
    ...account,
    balance: account.balance + (adjustments.get(account.id) || 0),
  }));
}

