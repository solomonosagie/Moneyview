function el(tag, className, text) {
  const node = document.createElement(tag);
  if (className) node.className = className;
  if (text != null) node.textContent = text;
  return node;
}

function emptyState(title, description, action) {
  const box = el("div", "remote-state remote-state-empty");
  box.append(el("strong", "", title), el("p", "", description));
  if (action) box.append(action);
  return box;
}

function accountSymbol(accountId) {
  if (accountId === "savings") return "savings-symbol";
  if (accountId === "card") return "card-symbol";
  return "current-symbol";
}

function iconFor(transaction) {
  if (transaction.type === "in") return "income-icon";
  const category = getCategoryLabel(transaction.category).toLowerCase();
  if (category === "groceries") return "groceries-icon";
  if (category === "transport") return "transport-icon";
  if (category === "transfer") return "transfer-icon";
  if (category === "utilities") return "utilities-icon";
  return "merchant-icon-neutral";
}

function transactionTable(rows, options = {}) {
  const columns = [
    { key: "description", label: "Transaction" },
    { key: "category", label: "Category" },
    { key: "date", label: "Date" },
    { key: "amount", label: "Amount" },
  ];
  const wrap = el("div", "mv-table-scroll");
  const table = el("table", "transaction-table mv-data-table");
  const caption = el(
    "caption",
    "sr-only",
    "Transactions with category, date, and amount direction.",
  );
  const thead = document.createElement("thead");
  const headRow = document.createElement("tr");

  columns.forEach(({ key, label }) => {
    const th = document.createElement("th");
    th.scope = "col";
    if (!options.onSort) {
      th.textContent = label;
    } else {
      const active = options.sortBy === key;
      if (active) th.setAttribute("aria-sort", options.sortDirection === "asc" ? "ascending" : "descending");
      const button = el("button", "mv-sort-button");
      button.type = "button";
      const nextDirection = active && options.sortDirection === "asc" ? "descending" : "ascending";
      button.setAttribute(
        "aria-label",
        `Sort by ${label.toLowerCase()}${active ? `, currently ${options.sortDirection === "asc" ? "ascending" : "descending"}` : ""}`,
      );
      button.append(document.createTextNode(label));
      const mark = el(
        "span",
        "mv-sort-mark",
        active ? (options.sortDirection === "asc" ? "↑" : "↓") : "↕",
      );
      mark.setAttribute("aria-hidden", "true");
      const hint = el(
        "span",
        "sr-only",
        active ? `Activate ${nextDirection} order` : "Activate sorting",
      );
      button.append(mark, hint);
      button.addEventListener("click", () => options.onSort(key));
      th.append(button);
    }
    headRow.append(th);
  });

  thead.append(headRow);
  const tbody = document.createElement("tbody");

  rows.forEach((transaction) => {
    const incoming = transaction.type === "in";
    const row = document.createElement("tr");
    row.id = `transaction-${transaction.id}`;
    row.dataset.transactionId = transaction.id;

    const nameCell = document.createElement("td");
    const name = el("div", "transaction-name-cell");
    const icon = el("span", `merchant-icon ${iconFor(transaction)}`);
    icon.setAttribute("aria-hidden", "true");
    icon.append(document.createElement("span"));
    const copy = el("span", "transaction-copy");
    copy.append(
      el("strong", "", transaction.description || "Untitled transaction"),
      el("small", "", incoming ? "Money in" : "Money out"),
    );
    name.append(icon, copy);
    nameCell.append(name);

    const categoryCell = document.createElement("td");
    categoryCell.append(el("span", "category-label", getCategoryLabel(transaction.category)));

    const dateCell = el("td", "mv-date-cell", formatDate(transaction.date));

    const amountCell = el("td", "transaction-amount");
    const tag = el("span", `direction-tag ${incoming ? "direction-in" : "direction-out"}`, incoming ? "Money in" : "Money out");
    const amount = el("strong", "", `${incoming ? "+" : "−"}${formatMoney(transaction.amount)}`);
    amountCell.append(tag, amount);

    row.append(nameCell, categoryCell, dateCell, amountCell);
    tbody.append(row);
  });

  table.append(caption, thead, tbody);
  wrap.append(table);
  return wrap;
}

